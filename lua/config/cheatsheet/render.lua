--- Rendering for the per-mode keymap cheatsheet.
---
--- Every section becomes a card (a bordered box with the section name in the
--- top border). Cards flow through a 1-3 column masonry; each row inside a card
--- shows a key and its description as a small table. All boxes share a single
--- accent colour while the key text is coloured per card, which gives each
--- group a visual identity without turning the page into a rainbow.
---
--- Everything is highlighted with extmarks, so no syntax files are involved.
local glyphs = require("config.cheatsheet.glyphs")

local M = {}

local ns = vim.api.nvim_create_namespace("config_cheatsheet")

--- Highlight groups sampled to find the theme's most colourful accent. The
--- accent palette is then generated by rotating its hue, so the colours are
--- always distinct and harmonise with the active colorscheme.
local ACCENT_BASES = {
  "Function",
  "Special",
  "Type",
  "DiagnosticInfo",
  "Identifier",
  "DiagnosticWarn",
  "DiagnosticError",
  "Statement",
  "Keyword",
  "Constant",
  "String",
  "Number",
  "DiagnosticHint",
  "PreProc",
  "Todo",
}

local ACCENT_COUNT = 8

--- Colour shared by every card box (border + title). `nil` follows the theme's
--- FloatBorder, which is a calm, neutral colour; set a "#rrggbb" string to
--- override. Only the bind text gets the multi-colour accent palette.
local BOX_COLOR = nil

--- Box-drawing characters are multi-byte; span offsets must account for that.
local VERT = "│"
local VW = #VERT

local HL = {
  title = "ConfigCheatsheetTitle",
  subtitle = "ConfigCheatsheetSubtitle",
  legend = "ConfigCheatsheetLegend",
  border = "ConfigCheatsheetBorder",
  box = "ConfigCheatsheetBox",
  box_title = "ConfigCheatsheetBoxTitle",
  motion = "ConfigCheatsheetMotion",
  desc = "ConfigCheatsheetDesc",
}

local function accent_name(index)
  return "ConfigCheatsheetAccent" .. index
end

local function rgb_to_hsl(r, g, b)
  r, g, b = r / 255, g / 255, b / 255
  local max, min = math.max(r, g, b), math.min(r, g, b)
  local l = (max + min) / 2
  local h, s = 0, 0
  if max ~= min then
    local d = max - min
    s = l > 0.5 and d / (2 - max - min) or d / (max + min)
    if max == r then
      h = (g - b) / d + (g < b and 6 or 0)
    elseif max == g then
      h = (b - r) / d + 2
    else
      h = (r - g) / d + 4
    end
    h = h / 6
  end
  return h, s, l
end

local function hue_to_rgb(p, q, t)
  if t < 0 then
    t = t + 1
  elseif t > 1 then
    t = t - 1
  end
  if t < 1 / 6 then
    return p + (q - p) * 6 * t
  elseif t < 1 / 2 then
    return q
  elseif t < 2 / 3 then
    return p + (q - p) * (2 / 3 - t) * 6
  end
  return p
end

local function hsl_to_hex(h, s, l)
  local r, g, b
  if s == 0 then
    r, g, b = l, l, l
  else
    local q = l < 0.5 and l * (1 + s) or l + s - l * s
    local p = 2 * l - q
    r = hue_to_rgb(p, q, h + 1 / 3)
    g = hue_to_rgb(p, q, h)
    b = hue_to_rgb(p, q, h - 1 / 3)
  end
  return string.format("#%02x%02x%02x", math.floor(r * 255 + 0.5), math.floor(g * 255 + 0.5), math.floor(b * 255 + 0.5))
end

local function to_rgb(value)
  return math.floor(value / 65536) % 256, math.floor(value / 256) % 256, value % 256
end

--- Build `ACCENT_COUNT` distinct accent colours from the theme's most
--- saturated group, adapted for a dark or light background.
local function build_accents()
  local base_hue, base_sat = nil, -1
  for _, name in ipairs(ACCENT_BASES) do
    local fg = vim.api.nvim_get_hl(0, { name = name, link = false }).fg
    if fg then
      local h, s = rgb_to_hsl(to_rgb(fg))
      if s > base_sat then
        base_sat, base_hue = s, h
      end
    end
  end

  local normal = vim.api.nvim_get_hl(0, { name = "Normal", link = false })
  local br, bg, bb = to_rgb(normal.bg or 0x000000)
  local dark = (0.299 * br + 0.587 * bg + 0.114 * bb) < 128

  base_hue = base_hue or 0.58
  local sat = math.min(math.max(base_sat, 0.5), 0.8)
  local light = dark and 0.7 or 0.42

  local colors = {}
  for i = 1, ACCENT_COUNT do
    colors[i] = hsl_to_hex((base_hue + (i - 1) / ACCENT_COUNT) % 1, sat, light)
  end
  return colors
end

--- One neutral colour for every box: the theme's border colour if available.
local function box_color()
  if BOX_COLOR then
    return tonumber(BOX_COLOR:gsub("^#", ""), 16)
  end
  for _, name in ipairs({ "FloatBorder", "Comment", "LineNr" }) do
    local fg = vim.api.nvim_get_hl(0, { name = name, link = false }).fg
    if fg then
      return fg
    end
  end
  return 0x8a919c
end

function M.setup_highlights()
  local links = {
    [HL.title] = "Title",
    [HL.subtitle] = "Comment",
    [HL.legend] = "Comment",
    [HL.border] = "FloatBorder",
    [HL.motion] = "Special",
    [HL.desc] = "Normal",
  }
  for name, link in pairs(links) do
    vim.api.nvim_set_hl(0, name, { default = true, link = link })
  end

  local accents = build_accents()
  for index, fg in ipairs(accents) do
    vim.api.nvim_set_hl(0, accent_name(index), { default = true, fg = fg, bold = true })
  end
  -- One shared colour for every box.
  local box = box_color()
  vim.api.nvim_set_hl(0, HL.box, { default = true, fg = box })
  vim.api.nvim_set_hl(0, HL.box_title, { default = true, fg = box, bold = true })
end

local function dwidth(text)
  return vim.api.nvim_strwidth(text or "")
end

local function rep(char, count)
  return string.rep(char, math.max(count, 0))
end

--- Truncate `text` to at most `width` display cells, adding an ellipsis.
local function fit(text, width)
  text = text or ""
  if width <= 0 then
    return ""
  end
  if dwidth(text) <= width then
    return text
  end
  local out = ""
  for _, char in ipairs(vim.fn.split(text, "\\zs")) do
    if dwidth(out) + dwidth(char) > width - 1 then
      return out .. "…"
    end
    out = out .. char
  end
  return out
end

--- Pad `text` with spaces to exactly `width` display cells (or leave longer).
local function pad_to(text, width)
  return text .. rep(" ", width - dwidth(text))
end

--- Pick a column count and a uniform card width for `width` cells.
local function layout(width)
  local gap = 2
  local ncols = 1
  if width >= 138 then
    ncols = 3
  elseif width >= 94 then
    ncols = 2
  end

  local max_content = 150
  local usable = math.max(width - 4, 34)
  local col_width = math.floor((usable - gap * (ncols - 1)) / ncols)
  local max_col = ncols == 1 and 96 or 66
  if ncols > 1 then
    max_col = math.min(max_col, math.floor((max_content - gap * (ncols - 1) - 4) / ncols))
  end
  col_width = math.max(30, math.min(col_width, max_col))
  local content = ncols * col_width + gap * (ncols - 1)
  return ncols, col_width, gap, content
end

--- Build a single card (box) for `section`.
---
--- Returns a list of lines and, per line, a list of `{ start, finish, hl }`
--- byte spans. `key_hl` colours this card's key text.
local function format_card(section, key_hl, col_width)
  local border_inner = col_width - 2
  local body = col_width - 4
  local title = fit(section.name or "", border_inner - 4)
  local label = "─ " .. title .. " "
  local top = "╭" .. label .. rep("─", border_inner - dwidth(label)) .. "╮"
  local bottom = "╰" .. rep("─", border_inner) .. "╯"

  -- Align keys into a column, leaving the rest for descriptions.
  local widest = 0
  for _, entry in ipairs(section.entries or {}) do
    local width = dwidth(glyphs.pretty(entry.key or "")) + (entry.motion and dwidth(" [m]") or 0)
    if width > widest then
      widest = width
    end
  end
  local key_col = math.min(widest, math.max(math.floor(body * 0.45), 6))

  local lines = { top }
  local title_start = #"╭─ "
  local spans = { { { 0, #top, HL.box } } }
  if #title > 0 then
    spans[1][#spans[1] + 1] = { title_start, title_start + #title, HL.box_title }
  end

  for _, entry in ipairs(section.entries or {}) do
    local base = glyphs.pretty(entry.key or "")
    local badge = entry.motion and " [m]" or ""
    local keycell = base .. badge
    local padw = math.max(key_col - dwidth(keycell), 1)
    local desc = fit(entry.desc or "", body - dwidth(keycell) - padw)
    local prefix = keycell .. rep(" ", padw)

    local line = VERT .. " " .. pad_to(prefix .. desc, body) .. " " .. VERT
    local rowspans = {
      { 0, VW, HL.box },
      { VW + 1, VW + 1 + #base, key_hl },
      { #line - VW, #line, HL.box },
    }
    if entry.motion then
      rowspans[#rowspans + 1] = { VW + 1 + #base, VW + 1 + #base + #badge, HL.motion }
    end
    if #desc > 0 then
      rowspans[#rowspans + 1] = { VW + 1 + #prefix, VW + 1 + #prefix + #desc, HL.desc }
    end

    lines[#lines + 1] = line
    spans[#spans + 1] = rowspans
  end

  lines[#lines + 1] = bottom
  spans[#spans + 1] = { { 0, #bottom, HL.box } }
  return lines, spans
end

--- Render `doc` into `buf`.
---
--- `doc` is `{ title, subtitle, legend, sections = { { name, entries = { { key, desc, motion } } } } }`.
--- `width` is the target window width (defaults to the full editor width).
function M.render(buf, doc, width)
  width = width or vim.o.columns
  local ncols, col_width, gap, content = layout(width)
  local margin = math.max(math.floor((width - content) / 2), 0)
  local pad = string.rep(" ", margin)

  local lines = {}
  local marks = {}

  local function add(text, spans)
    lines[#lines + 1] = pad .. text
    local row = #lines - 1
    if spans and #spans > 0 then
      local shifted = {}
      for _, span in ipairs(spans) do
        shifted[#shifted + 1] = { span[1] + margin, span[2] + margin, span[3] }
      end
      marks[row] = shifted
    end
  end

  local function add_centered(text, hl)
    local value = fit(text, content)
    local left = math.max(math.floor((content - dwidth(value)) / 2), 0)
    add(rep(" ", left) .. value, { { left, left + #value, hl } })
  end

  -- Title, subtitle and legend ---------------------------------------------
  local title = doc.title or "Cheatsheet"
  local inner = math.max(content - 2, 10)
  local box_top = "╭" .. rep("─", inner) .. "╮"
  local box_bottom = "╰" .. rep("─", inner) .. "╯"
  add(box_top, { { 0, #box_top, HL.border } })

  local shown = fit(title, inner)
  local title_left = math.max(math.floor((inner - dwidth(shown)) / 2), 0)
  local mid = VERT .. rep(" ", title_left) .. shown .. rep(" ", inner - dwidth(shown) - title_left) .. VERT
  add(mid, {
    { 0, VW, HL.border },
    { VW + title_left, VW + title_left + #shown, HL.title },
    { #mid - VW, #mid, HL.border },
  })
  add(box_bottom, { { 0, #box_bottom, HL.border } })
  add("")

  if doc.subtitle then
    add_centered(doc.subtitle, HL.subtitle)
  end
  for _, line in ipairs(doc.legend or {}) do
    add_centered(line, HL.legend)
  end
  add("")

  -- Masonry: drop each card into the shortest column -------------------------
  local columns = {}
  local heights = {}
  for c = 1, ncols do
    columns[c] = {}
    heights[c] = 0
  end

  for index, section in ipairs(doc.sections or {}) do
    if #(section.entries or {}) > 0 then
      local target = 1
      for c = 2, ncols do
        if heights[c] < heights[target] then
          target = c
        end
      end

      local key_hl = accent_name(((index - 1) % ACCENT_COUNT) + 1)
      local card_lines, card_spans = format_card(section, key_hl, col_width)

      if heights[target] > 0 then
        columns[target][#columns[target] + 1] = { text = rep(" ", col_width), spans = {} }
        heights[target] = heights[target] + 1
      end
      for li, line in ipairs(card_lines) do
        columns[target][#columns[target] + 1] = { text = line, spans = card_spans[li] }
      end
      heights[target] = heights[target] + #card_lines
    end
  end

  local rows = 0
  for c = 1, ncols do
    rows = math.max(rows, heights[c])
  end

  local gapstr = rep(" ", gap)
  for r = 1, rows do
    local cells = {}
    local spans = {}
    local col_byte = 0
    for c = 1, ncols do
      local item = columns[c][r]
      local text = item and item.text or rep(" ", col_width)
      cells[#cells + 1] = text
      if item then
        for _, span in ipairs(item.spans) do
          spans[#spans + 1] = { col_byte + span[1], col_byte + span[2], span[3] }
        end
      end
      col_byte = col_byte + #text + gap
    end
    add(table.concat(cells, gapstr), spans)
  end

  vim.bo[buf].modifiable = true
  vim.api.nvim_buf_set_lines(buf, 0, -1, false, lines)
  vim.api.nvim_buf_clear_namespace(buf, ns, 0, -1)
  for row, spans in pairs(marks) do
    for _, span in ipairs(spans) do
      pcall(vim.api.nvim_buf_set_extmark, buf, ns, row, span[1], {
        end_col = span[2],
        hl_group = span[3],
        hl_mode = "combine",
      })
    end
  end
  vim.bo[buf].modifiable = false
  vim.bo[buf].modified = false
end

return M
